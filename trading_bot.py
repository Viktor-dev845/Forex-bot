    def check_exits(self):
        """
        Lightweight check running every second.
        Safely monitors Stop-Loss and Take-Profit using real-time WebSocket prices.
        And GLOBAL DRAWDOWN (Equity Guard).
        """
        try:
            # Only check if we have active positions
            active_symbols = [s for s, pos in self.positions.items() if pos is not None]
            if not active_symbols:
                return

            # Use WebSocket for real-time prices if available, else skip (will be checked in main cycle)
            if not self.websocket_client or not self.websocket_client.is_connected():
                return
            
            for symbol in active_symbols:
                try:
                    position_info = self.positions[symbol]
                    
                    # Get real-time price from WebSocket
                    current_price = self.websocket_client.get_latest_price(symbol)
                    if current_price is None:
                        continue  # No price data yet
                    
                    # Check SL/TP thresholds
                    sl_price = position_info.get('sl_price')
                    tp_price = position_info.get('tp_price')
                    position_side = position_info['side']
                    
                    should_close = False
                    exit_reason = ""
                    
                    if position_side == 'long':
                        if sl_price and current_price <= sl_price:
                            should_close = True
                            exit_reason = f"STOP-LOSS HIT @ {current_price:.4f} (SL: {sl_price:.4f})"
                        elif tp_price and current_price >= tp_price:
                            should_close = True
                            exit_reason = f"TAKE-PROFIT HIT @ {current_price:.4f} (TP: {tp_price:.4f})"
                    else:  # short
                        if sl_price and current_price >= sl_price:
                            should_close = True
                            exit_reason = f"STOP-LOSS HIT @ {current_price:.4f} (SL: {sl_price:.4f})"
                        elif tp_price and current_price <= tp_price:
                            should_close = True
                            exit_reason = f"TAKE-PROFIT HIT @ {current_price:.4f} (TP: {tp_price:.4f})"
                    
                    # Also check trailing stop
                    if not should_close:
                        trailing_result = self.risk_manager.update_trailing_stop(symbol, current_price)
                        if trailing_result['triggered']:
                            should_close = True
                            exit_reason = f"TRAILING STOP HIT @ {current_price:.4f} (Stop: {trailing_result['stop_level']:.4f})"
                    
                    # Execute close if triggered
                    if should_close:
                        self.monitor.logger.warning(f"[{symbol}] {exit_reason}")
                        
                        qty = position_info['qty']
                        close_side = OrderSide.SELL if position_side == 'long' else OrderSide.BUY
                        
                        try:
                            order = None
                            if hasattr(self.executor, 'close_position') and self.market_type in ['forex', 'synthetics']:
                                success = self.executor.close_position(symbol, position_info.get('order_id'))
                                if success:
                                    order = Order(id=str(position_info.get('order_id')), symbol=symbol, side=close_side, quantity=qty, order_type="market", status=OrderStatus.FILLED, filled_price=current_price)
                            
                            if not order:
                                order = self.executor.submit_order(symbol, close_side, qty, order_type="market")
                            
                            if order and order.status == OrderStatus.FILLED:
                                # Calculate PnL
                                entry = self.entry_prices.get(symbol, current_price)
                                if position_side == 'long':
                                    pnl = (current_price - entry) * qty
                                else:
                                    pnl = (entry - current_price) * qty
                                
                                self.daily_pnl += pnl
                                
                                trade_record = TradeRecord(
                                    timestamp=datetime.now().isoformat(),
                                    symbol=symbol,
                                    side='CLOSE',
                                    quantity=qty,
                                    price=current_price,
                                    order_id=order.id,
                                    pnl=pnl,
                                    notes=f"WebSocket Exit: {exit_reason}"
                                )
                                self.monitor.log_trade(trade_record)
                                
                                # Record result for retraining
                                self.retrainer.record_result(symbol, pnl)
                                
                                # Clear position
                                self.positions[symbol] = None
                                self.entry_prices[symbol] = 0
                                self.risk_manager.close_position(symbol, current_price)
                                
                        except Exception as e:
                            self.monitor.logger.error(f"Failed to close position for {symbol}: {e}")
                
                except Exception as e:
                    self.monitor.logger.error(f"Error checking exit for {symbol}: {e}")
                    continue

        except Exception as e:
            # Prevent one error from crashing the heartbeat
            if isinstance(e, SystemExit):
                raise e
            self.monitor.logger.error(f"Error in check_exits: {e}") 

    def check_binary_outcomes(self):
        """Asynchronously polls IQ Option for trade results to update Martingale and PnL."""
        if self.market_type != 'iqoption' or not self.pending_binary_orders:
            return
            
        import time
        completed_orders = []
        for order_id, order_info in self.pending_binary_orders.items():
            elapsed = time.time() - order_info['timestamp']
            
            expiration_seconds = self.config.get('bot', {}).get('expiration_time_minutes', 2) * 60
            if elapsed > expiration_seconds + 5:
                symbol = order_info['symbol']
                qty = order_info['qty']
                
                # FORCE CLEAR POSITION ON MAIN THREAD SO IT CAN TAKE NEW TRADES INSTANTLY
                if symbol in self.positions:
                    self.positions[symbol] = None
                self.entry_prices[symbol] = None
                completed_orders.append(order_id)
                
                # Offload buggy IQ Option API check to a fire-and-forget background thread
                def _bg_check(oid, sym, amount):
                    try:
                        # Fallback to the strict check_win_v3 which blocks but gets the result
                        res, prof = self.executor.api.check_win_v3(int(oid))
                        actual_pnl = 0.0
                        if res == 'win':
                            self.monitor.logger.info(f"[{sym}] BINARY WIN (+${prof:.2f}). Resetting Martingale.")
                            self.martingale_multiplier = 1
                            self.daily_pnl += prof
                            actual_pnl = prof
                        elif res == 'equal':
                            self.monitor.logger.info(f"[{sym}] BINARY TIE ($0). Keeping Martingale.")
                            actual_pnl = 0.0
                        else:
                            self.monitor.logger.warning(f"[{sym}] BINARY LOSS (-${amount:.2f}). Doubling Martingale.")
                            self.martingale_multiplier = min(self.martingale_multiplier * 2.0, 8.0)
                            self.daily_pnl -= amount
                            actual_pnl = -amount

                        if self.daily_profit_target > 0 and self.daily_pnl >= self.daily_profit_target:
                            self.trading_halted = True
                            self.monitor.logger.info(
                                f"DAILY PROFIT TARGET HIT: ${self.daily_pnl:+.2f} "
                                f"(target ${self.daily_profit_target:.2f}). "
                                "Trading paused until the next trading day."
                            )
                        elif self.daily_loss_limit > 0 and self.daily_pnl <= -self.daily_loss_limit:
                            self.trading_halted = True
                            self.monitor.logger.warning(
                                f"DAILY LOSS LIMIT HIT: ${self.daily_pnl:+.2f} "
                                f"(limit ${self.daily_loss_limit:.2f}). "
                                "Trading paused until the next trading day."
                            )
                            
                        # UPDATE DATABASE
                        self.monitor.update_trade(str(oid), actual_pnl)
                        
                        # SAVE STATE & NOTIFY WS
                        self.save_state()
                        self._notify_dashboard()
                        
                    except Exception as e:
                        self.monitor.logger.error(f"Error checking binary win: {e}")
                        

                import threading
                t = threading.Thread(target=_bg_check, args=(order_id, symbol, qty))
                t.daemon = True
                t.start()
                    
        for oid in completed_orders:
            if oid in self.pending_binary_orders:
                del self.pending_binary_orders[oid]

