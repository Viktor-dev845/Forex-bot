    def _trigger_initial_training(self, symbol: str):
        """Adds a symbol to the initial training queue and starts the worker thread if not running."""
        if self.retrainer.is_training.get(symbol, False) or symbol in self.initial_training_queue:
            return # Already training or queued
            
        self.retrainer.is_training[symbol] = True
        self.initial_training_queue.append(symbol)
        
        if not self.initial_training_thread_running:
            self.initial_training_thread_running = True
            import threading
            t = threading.Thread(target=self._process_initial_training_queue)
            t.daemon = True
            t.start()
            
    def _process_initial_training_queue(self):
        """Processes the training queue sequentially to avoid freezing the system."""
        import subprocess, sys
        while self.initial_training_queue:
            symbol = self.initial_training_queue.pop(0)
            self.monitor.logger.info(f"[{symbol}] Starting SEQUENTIAL initial training...")
            try:
                self.monitor.logger.info(f"[{symbol}] Fetching data (running in background)...")
                fetch_result = subprocess.run([sys.executable, "fetch_massive_data.py", "--symbol", symbol], capture_output=True, text=True)
                if fetch_result.returncode != 0:
                    raise RuntimeError(f"Data fetch failed: {fetch_result.stderr[-500:]}")
                
                self.monitor.logger.info(f"[{symbol}] Training XGBoost (running in background)...")
                xgb_result = subprocess.run([sys.executable, "train_model.py", "--symbol", symbol], capture_output=True, text=True)
                if xgb_result.returncode != 0:
                    raise RuntimeError(f"XGBoost training failed: {xgb_result.stderr[-500:]}")
                
                self.monitor.logger.info(f"[{symbol}] Training LSTM (running in background)...")
                lstm_result = subprocess.run([sys.executable, "train.py", "--ticker", symbol, "--model", "lstm", "--epochs", "10"], capture_output=True, text=True)
                if lstm_result.returncode != 0:
                    raise RuntimeError(f"LSTM training failed: {lstm_result.stderr[-500:]}")
                
                self.monitor.logger.info(f"[{symbol}] Training Transformer (running in background)...")
                trans_result = subprocess.run([sys.executable, "train.py", "--ticker", symbol, "--model", "transformer", "--epochs", "10"], capture_output=True, text=True)
                if trans_result.returncode != 0:
                    raise RuntimeError(f"Transformer training failed: {trans_result.stderr[-500:]}")

                expected_files = [f"models/{symbol}_xgboost.json", f"models/{symbol}_lstm.pth", f"models/{symbol}_transformer.pth"]
                missing_files = [path for path in expected_files if not os.path.exists(path)]
                if missing_files:
                    raise RuntimeError(f"Training completed without expected model files: {missing_files}")
                
                self.monitor.logger.info(f"[{symbol}] Initial training complete! Queued for reload.")
                self.retrainer.reload_needed.add(symbol)
            except Exception as e:
                self.monitor.logger.error(f"[{symbol}] Initial training failed: {e}")
            finally:
                self.retrainer.is_training[symbol] = False
                
        self.initial_training_thread_running = False
    def prepare_features(self, df: pd.DataFrame, model_type: str, symbol: str):
        preprocessor = self.preprocessors.get(model_type)
        if not preprocessor:
            return None

        try:
            if model_type == 'xgboost':
                df_features = preprocessor.generate_features(df)
                ignore_cols = ['Target', 'Future_Return', 'Date', 'index', 'Open', 'High', 'Low', 'Close', 'Volume']
                feature_cols = [c for c in df_features.columns if c not in ignore_cols]
                return df_features[feature_cols] if not df_features.empty else None
            
            elif model_type in ['lstm', 'transformer']:
                df_features = preprocessor.generate_features(df)
                
                # Normalize numeric columns (MUST use same scaler as training!)
                feature_columns = [col for col in df_features.columns if df_features[col].dtype in ['float64', 'int64', 'float32', 'int32']]
                feature_columns = [col for col in feature_columns if col not in ['Date', 'Datetime']]
                
                # Load the scaler saved during training for the SPECIFIC symbol
                scaler_path = f"models/{symbol}_scaler.gz"
                
                if os.path.exists(scaler_path):
                    import joblib
                    import warnings
                    scaler = joblib.load(scaler_path)
                    
                    # Ensure exact feature alignment
                    if hasattr(scaler, 'feature_names_in_'):
                        feature_columns = list(scaler.feature_names_in_)
                        for col in feature_columns:
                            if col not in df_features.columns:
                                df_features[col] = 0.0
                    
                    # Transform while keeping column names to avoid StandardScaler warnings
                    with warnings.catch_warnings():
                        warnings.simplefilter("ignore")
                        df_features[feature_columns] = scaler.transform(df_features[feature_columns])
                    
                    data_scaled = df_features[feature_columns].values
                    self.monitor.logger.debug(f"{model_type.upper()}: Using saved scaler from {scaler_path}")
                else:
                    # Fallback: Create new scaler (but log warning)
                    self.monitor.logger.warning(f"{model_type.upper()} Scaler not found at {scaler_path}. Using fit_transform (predictions may be unreliable!)")
                    from sklearn.preprocessing import StandardScaler
                    scaler = StandardScaler()
                    # Transform dataframe to avoid warnings, then get values
                    df_features[feature_columns] = scaler.fit_transform(df_features[feature_columns])
                    data_scaled = df_features[feature_columns].values
                
                return data_scaled

        except Exception as e:
            self.monitor.logger.error(f"Error preparing features for {model_type}: {e}")
            return None

    def make_prediction(self, features, model, model_type: str) -> float:
        if features is None or len(features) == 0:
            self.monitor.logger.warning(f"{model_type}: No features provided")
            return None

        if not model:
            self.monitor.logger.warning(f"{model_type}: Model not loaded")
            return None
            
        try:
            if model_type == 'xgboost':
                latest_features = features.iloc[[-1]]
                probs = model.predict(latest_features) # returns prob of class 1
                return float(probs[0])
            
            elif model_type in ['lstm', 'transformer']:
                import torch
                if len(features) < self.seq_length:
                    self.monitor.logger.warning(f"{model_type.upper()}: Insufficient data ({len(features)} < {self.seq_length} required)")
                    return None
                    
                sequence = features[-self.seq_length:]
                X_tensor = torch.FloatTensor(sequence).unsqueeze(0)
                with torch.no_grad():
                    logits = model(X_tensor)
                    prediction = torch.sigmoid(logits).item()
                return prediction

        except Exception as e:
            self.monitor.logger.critical(f"[FAIL] MODEL FAILURE ({model_type}): {e}")
            import traceback
            self.monitor.logger.error(traceback.format_exc())
            return None
        
        return None

    def save_market_data(self, symbol, new_df):
        """Append new data to local CSV storage for retraining."""
        if new_df is None or new_df.empty:
            return
            
        data_dir = "data/raw"
        if not os.path.exists(data_dir):
            os.makedirs(data_dir)
            
        file_path = f"{data_dir}/{symbol}.csv"
        
        try:
            if os.path.exists(file_path):
                # Load existing
                existing_df = pd.read_csv(file_path, index_col=0, parse_dates=True)
                existing_df.index = pd.to_datetime(existing_df.index, utc=True, errors='coerce')
                normalized_new_df = new_df.copy()
                normalized_new_df.index = pd.to_datetime(normalized_new_df.index, utc=True, errors='coerce')
                existing_df = existing_df[~existing_df.index.isna()]
                normalized_new_df = normalized_new_df[~normalized_new_df.index.isna()]
                # Combine
                combined_df = pd.concat([existing_df, normalized_new_df])
                # Drop duplicates based on index
                combined_df = combined_df[~combined_df.index.duplicated(keep='last')]
                combined_df.sort_index(inplace=True)
                combined_df.to_csv(file_path)
            else:
                normalized_new_df = new_df.copy()
                normalized_new_df.index = pd.to_datetime(normalized_new_df.index, utc=True, errors='coerce')
                normalized_new_df = normalized_new_df[~normalized_new_df.index.isna()]
                normalized_new_df.to_csv(file_path)
        except Exception as e:
            self.monitor.logger.error(f"Error updating CSV for {symbol}: {e}")

    def _fetch_iqoption_data_live(self, symbol, time_interval, max_candles):
        """Fetches candles using the existing connected API instance to prevent rate limits."""
        try:
            granularity_map = {"1m": 60, "2m": 120, "5m": 300, "15m": 900}
            interval = granularity_map.get(time_interval, 120)
            import time
            import concurrent.futures
            
            # Wrap the blocking IQ Option API call in a thread with a 10-second timeout
            with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
                future = executor.submit(self.executor.api.get_candles, symbol, interval, max_candles, time.time())
                try:
                    candles = future.result(timeout=10)
                except concurrent.futures.TimeoutError:
                    self.monitor.logger.error(f"Timeout while fetching candles for {symbol}")
                    return None
                    
            if not candles:
                return None
            df = pd.DataFrame(candles)
            df['Date'] = pd.to_datetime(df['from'], unit='s')
            df.set_index('Date', inplace=True)
            df.rename(columns={'max': 'High', 'min': 'Low', 'open': 'Open', 'close': 'Close', 'volume': 'Volume'}, inplace=True)
            df.drop(['id', 'from', 'at', 'to'], axis=1, inplace=True, errors='ignore')
            return df
        except Exception as e:
            self.monitor.logger.error(f"Error fetching live data: {e}")
            return None

